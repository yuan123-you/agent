package com.aimall.backend.address;

import com.aimall.backend.common.BizException;
import com.aimall.backend.entity.Address;
import com.aimall.backend.mapper.AddressMapper;
import com.baomidou.mybatisplus.core.MybatisConfiguration;
import com.baomidou.mybatisplus.extension.spring.MybatisSqlSessionFactoryBean;
import org.apache.ibatis.session.SqlSessionFactory;
import org.junit.jupiter.api.*;
import org.mybatis.spring.mapper.MapperFactoryBean;
import org.springframework.context.annotation.*;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.jdbc.datasource.*;
import org.springframework.transaction.PlatformTransactionManager;
import org.springframework.transaction.annotation.EnableTransactionManagement;
import javax.sql.DataSource;
import java.math.BigDecimal;
import java.lang.reflect.*;
import java.util.*;
import java.util.concurrent.*;
import static org.junit.jupiter.api.Assertions.*;

class AddressConcurrencyTransactionTest {
    static class Gate {
        volatile CountDownLatch snapshot, release;
        volatile boolean failInsert;
        final java.util.concurrent.atomic.AtomicBoolean first = new java.util.concurrent.atomic.AtomicBoolean(true);
    }
    @Configuration
    @EnableTransactionManagement(proxyTargetClass = true)
    static class Config {
        @Bean DataSource dataSource() { return new DriverManagerDataSource("jdbc:h2:mem:address_" + UUID.randomUUID()
                + ";MODE=MySQL;DB_CLOSE_DELAY=-1;LOCK_TIMEOUT=10000", "sa", ""); }
        @Bean JdbcTemplate jdbc(DataSource ds) { return new JdbcTemplate(ds); }
        @Bean PlatformTransactionManager transactionManager(DataSource ds) { return new DataSourceTransactionManager(ds); }
        @Bean SqlSessionFactory factory(DataSource ds) throws Exception {
            var bean = new MybatisSqlSessionFactoryBean(); bean.setDataSource(ds);
            var config = new MybatisConfiguration(); config.setMapUnderscoreToCamelCase(true); bean.setConfiguration(config);
            return bean.getObject();
        }
        @Bean MapperFactoryBean<AddressMapper> addresses(SqlSessionFactory f) {
            var bean = new MapperFactoryBean<>(AddressMapper.class); bean.setSqlSessionFactory(f); return bean;
        }
        @Bean Gate gate() { return new Gate(); }
        @Bean AddressService service(AddressMapper mapper, Gate gate) {
            AddressMapper observed = (AddressMapper) Proxy.newProxyInstance(AddressMapper.class.getClassLoader(),
                new Class<?>[]{AddressMapper.class}, (proxy,method,args) -> {
                    if (method.getName().equals("insert") && gate.failInsert) throw new IllegalStateException("injected address insert failure");
                    Object result;
                    try { result=method.invoke(mapper,args); } catch (InvocationTargetException e) { throw e.getCause(); }
                    if (method.getName().equals("selectCount") && gate.snapshot != null && gate.first.compareAndSet(true,false)) {
                        gate.snapshot.countDown();
                        if (!gate.release.await(5,TimeUnit.SECONDS)) throw new AssertionError("address snapshot timeout");
                    }
                    return result;
                });
            return new AddressService(observed);
        }
    }
    private AnnotationConfigApplicationContext context;
    private JdbcTemplate jdbc;
    private AddressService service;
    private Gate gate;
    @BeforeEach void setup() {
        context = new AnnotationConfigApplicationContext(Config.class); jdbc = context.getBean(JdbcTemplate.class);
        service = context.getBean(AddressService.class); gate = context.getBean(Gate.class);
        table("user_address",Address.class);
        jdbc.execute("create table sys_user(id bigint primary key, deleted integer default 0)");
        jdbc.update("insert into sys_user(id) values(7),(8)");
    }
    private void table(String name, Class<?> entity) {
        var columns = new ArrayList<String>();
        for (var field : entity.getDeclaredFields()) {
            if (java.lang.reflect.Modifier.isStatic(field.getModifiers())) continue;
            String column = field.getName().replaceAll("([a-z0-9])([A-Z])", "$1_$2").toLowerCase(Locale.ROOT);
            Class<?> t = field.getType();
            String type = t == Boolean.class ? "boolean" : t == Long.class ? "bigint" : t == Integer.class ? "integer" : t == BigDecimal.class ? "decimal(18,2)"
                    : t == java.time.LocalDateTime.class ? "timestamp" : "varchar(4096)";
            columns.add(column + (column.equals("id") ? " bigint generated by default as identity primary key" : " " + type)
                    + (column.equals("deleted") ? " default 0" : ""));
        }
        jdbc.execute("create table " + name + "(" + String.join(",", columns) + ")");
    }
    @AfterEach void close() { jdbc.execute("drop all objects"); context.close(); }
    private AddressDtos.AddressRequest request(boolean isDefault) {
        var r=new AddressDtos.AddressRequest(); r.setName("Receiver"); r.setPhone("13800000000");
        r.setAddress("Test address"); r.setIsDefault(isDefault); return r;
    }
    @Test void concurrentFirstAddressesHaveExactlyOneDefault() throws Exception {
        gate.snapshot=new CountDownLatch(1); gate.release=new CountDownLatch(1);
        var pool=Executors.newFixedThreadPool(2);
        try {
            var first=pool.submit(() -> service.add(7L,request(false)));
            assertTrue(gate.snapshot.await(5,TimeUnit.SECONDS));
            var started=new CountDownLatch(1);
            var second=pool.submit(() -> { started.countDown(); return service.add(7L,request(false)); });
            assertTrue(started.await(5,TimeUnit.SECONDS));
            // Before the fix the second insert commits while the first still sees an empty address book.
            try { second.get(500,TimeUnit.MILLISECONDS); } catch (TimeoutException blockedByUserLock) { }
            gate.release.countDown(); first.get(10,TimeUnit.SECONDS); second.get(10,TimeUnit.SECONDS);
            assertEquals(2,jdbc.queryForObject("select count(*) from user_address where user_id=7 and deleted=0",Integer.class));
            assertEquals(1,jdbc.queryForObject("select count(*) from user_address where user_id=7 and deleted=0 and is_default=true",Integer.class));
        } finally { gate.release.countDown(); pool.shutdownNow(); }
    }
    @Test void foreignOwnerCannotReadUpdateDeleteOrSelectDefault() {
        long id=service.add(8L,request(false)).getId();
        assertThrows(BizException.class,() -> service.forOrder(7L,id));
        assertThrows(BizException.class,() -> service.update(7L,id,request(true)));
        assertThrows(BizException.class,() -> service.delete(7L,id));
        assertThrows(BizException.class,() -> service.setDefault(7L,id));
        assertEquals(8L,service.forOrder(8L,id).getUserId());
        assertTrue(service.defaultFor(8L).getIsDefault());
    }
    @Test void deletingDefaultPromotesOneRemainingOwnedAddress() {
        long first=service.add(7L,request(false)).getId();
        long second=service.add(7L,request(false)).getId();
        long foreign=service.add(8L,request(false)).getId();
        service.delete(7L,first);
        assertEquals(second,service.defaultFor(7L).getId());
        assertEquals(foreign,service.defaultFor(8L).getId());
    }
    @Test void failedDefaultInsertRollsBackClearedDefault() {
        long first=service.add(7L,request(false)).getId(); gate.failInsert=true;
        assertThrows(IllegalStateException.class,() -> service.add(7L,request(true)));
        assertEquals(first,service.defaultFor(7L).getId());
        assertEquals(1,service.list(7L).size());
    }
    @Test void concurrentDefaultSwitchesLeaveExactlyOneOwnedDefault() throws Exception {
        long first=service.add(7L,request(false)).getId(); long second=service.add(7L,request(false)).getId();
        long foreign=service.add(8L,request(false)).getId();
        var pool=Executors.newFixedThreadPool(2); var start=new CyclicBarrier(2);
        try {
            var a=pool.submit(() -> { start.await(); service.setDefault(7L,first); return true; });
            var b=pool.submit(() -> { start.await(); service.setDefault(7L,second); return true; });
            assertTrue(a.get(10,TimeUnit.SECONDS)); assertTrue(b.get(10,TimeUnit.SECONDS));
            assertEquals(1,jdbc.queryForObject("select count(*) from user_address where user_id=7 and deleted=0 and is_default=true",Integer.class));
            assertEquals(foreign,service.defaultFor(8L).getId());
        } finally { pool.shutdownNow(); }
    }

}
