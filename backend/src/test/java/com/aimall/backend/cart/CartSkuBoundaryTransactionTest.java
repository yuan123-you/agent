package com.aimall.backend.cart;

import com.aimall.backend.common.BizException;
import com.aimall.backend.entity.OrderInfo;
import com.aimall.backend.mapper.*;
import com.aimall.backend.order.OrderService;
import com.baomidou.mybatisplus.core.MybatisConfiguration;
import com.baomidou.mybatisplus.extension.spring.MybatisSqlSessionFactoryBean;
import org.apache.ibatis.session.SqlSessionFactory;
import org.junit.jupiter.api.*;
import org.mybatis.spring.mapper.MapperFactoryBean;
import org.springframework.context.annotation.*;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.jdbc.datasource.*;
import org.springframework.transaction.PlatformTransactionManager;
import org.springframework.transaction.annotation.EnableTransactionManagement;
import javax.sql.DataSource;
import java.math.BigDecimal;
import java.util.*;
import static org.junit.jupiter.api.Assertions.*;
import static org.mockito.ArgumentMatchers.*;
import static org.mockito.Mockito.*;

class CartSkuBoundaryTransactionTest {
    @Configuration
    @EnableTransactionManagement(proxyTargetClass = true)
    static class Config {
        @Bean DataSource dataSource() { return new DriverManagerDataSource("jdbc:h2:mem:cart_sku_" + UUID.randomUUID()
                + ";MODE=MySQL;DB_CLOSE_DELAY=-1;LOCK_TIMEOUT=10000", "sa", ""); }
        @Bean JdbcTemplate jdbc(DataSource ds) { return new JdbcTemplate(ds); }
        @Bean PlatformTransactionManager transactionManager(DataSource ds) { return new DataSourceTransactionManager(ds); }
        @Bean SqlSessionFactory factory(DataSource ds) throws Exception {
            var bean = new MybatisSqlSessionFactoryBean(); bean.setDataSource(ds);
            var config = new MybatisConfiguration(); config.setMapUnderscoreToCamelCase(true); bean.setConfiguration(config);
            return bean.getObject();
        }
        @Bean MapperFactoryBean<CartItemMapper> carts(SqlSessionFactory f) { return mapper(CartItemMapper.class, f); }
        @Bean MapperFactoryBean<ProductMapper> products(SqlSessionFactory f) { return mapper(ProductMapper.class, f); }
        @Bean MapperFactoryBean<MallSkuMapper> skus(SqlSessionFactory f) { return mapper(MallSkuMapper.class, f); }
        private <T> MapperFactoryBean<T> mapper(Class<T> type, SqlSessionFactory f) {
            var bean = new MapperFactoryBean<>(type); bean.setSqlSessionFactory(f); return bean;
        }
        @Bean OrderService orders() {
            var orders = mock(OrderService.class); var order = new OrderInfo(); order.setId(10L);
            order.setOrderNo("boundary-test"); order.setTotalAmount(BigDecimal.TEN); order.setStatus("PENDING_PAYMENT");
            when(orders.checkout(anyLong(), anyList(), any(), any(), any(), any(), any())).thenReturn(order);
            return orders;
        }
        @Bean CartController controller(CartItemMapper c, ProductMapper p, MallSkuMapper s, OrderService o) {
            return new CartController(c, p, s, o);
        }
    }
    private AnnotationConfigApplicationContext context;
    private JdbcTemplate jdbc;
    private CartController controller;
    @BeforeEach void setup() {
        context = new AnnotationConfigApplicationContext(Config.class);
        jdbc = context.getBean(JdbcTemplate.class); controller = context.getBean(CartController.class);
        table("product", com.aimall.backend.entity.Product.class);
        table("mall_sku", com.aimall.backend.entity.MallSku.class);
        table("cart_item", com.aimall.backend.entity.CartItem.class);
        jdbc.execute("alter table cart_item add unique(user_id,product_id,sku_id)");
        jdbc.update("insert into product(id,name,status,price,stock,deleted) values(1,'Product','ON_SALE',10,100,0)");
        jdbc.update("insert into mall_sku(id,product_id,status,price,stock,lock_stock,deleted) values(11,1,'ENABLE',10,3,0,0),(12,1,'ENABLE',20,8,0,0)");
    }
    private void table(String name, Class<?> entity) {
        var columns = new ArrayList<String>();
        for (var field : entity.getDeclaredFields()) {
            if (java.lang.reflect.Modifier.isStatic(field.getModifiers())) continue;
            String column = field.getName().replaceAll("([a-z0-9])([A-Z])", "$1_$2").toLowerCase(Locale.ROOT);
            Class<?> t = field.getType();
            String type = t == Long.class ? "bigint" : t == Integer.class ? "integer" : t == BigDecimal.class ? "decimal(18,2)"
                    : t == java.time.LocalDateTime.class ? "timestamp" : "varchar(4096)";
            columns.add(column + (column.equals("id") ? " bigint generated by default as identity primary key" : " " + type)
                    + (column.equals("deleted") ? " default 0" : ""));
        }
        jdbc.execute("create table " + name + "(" + String.join(",", columns) + ")");
    }
    @AfterEach void close() { jdbc.execute("drop all objects"); context.close(); }
    private void row(long id, long user, long sku, int qty) {
        jdbc.update("insert into cart_item(id,user_id,product_id,sku_id,quantity,checked) values(?,?,1,?,?,1)",id,user,sku,qty);
    }
    @Test void explicitCheckoutOnlyClearsPurchasedSkuAndOwner() {
        row(1,7,11,2); row(2,7,12,2); row(3,8,11,2);
        var item = new CartController.CheckoutItemBody(); item.setProductId(1L); item.setSkuId(11L); item.setQuantity(1);
        var body = new CartController.CheckoutBody(); body.setItems(List.of(item));
        controller.checkout(7L,body);
        assertEquals(List.of(1,2,2),jdbc.queryForList("select quantity from cart_item order by id",Integer.class));
    }
    private CartController.AddBody addBody(int quantity) {
        var body = new CartController.AddBody(); body.setProductId(1L); body.setSkuId(11L); body.setQuantity(quantity); return body;
    }
    @Test void firstAddCannotExceedSkuStock() {
        assertEquals(2006,assertThrows(BizException.class,() -> controller.add(7L,addBody(4))).getCode());
        assertEquals(0,jdbc.queryForObject("select count(*) from cart_item",Integer.class));
    }
    @Test void accumulatedAddCannotExceedSkuStock() {
        row(1,7,11,2);
        assertThrows(BizException.class,() -> controller.add(7L,addBody(2)));
        assertEquals(2,jdbc.queryForObject("select quantity from cart_item where id=1",Integer.class));
    }
    @Test void quantityUpdateCannotExceedSkuStockOrUseDisabledSku() {
        row(1,7,11,2);
        assertThrows(BizException.class,() -> controller.update(7L,1L,Map.of("quantity",4,"checked",false)));
        jdbc.update("update mall_sku set status='DISABLE' where id=11");
        assertThrows(BizException.class,() -> controller.update(7L,1L,Map.of("quantity",1)));
        assertEquals(2,jdbc.queryForObject("select quantity from cart_item where id=1",Integer.class));
        assertEquals(1,jdbc.queryForObject("select checked from cart_item where id=1",Integer.class));
    }
    @Test void concurrentAddsRespectSkuStockBoundary() throws Exception {
        row(1,7,11,1);
        var pool = java.util.concurrent.Executors.newFixedThreadPool(2);
        var start = new java.util.concurrent.CyclicBarrier(2);
        java.util.concurrent.Callable<Boolean> add = () -> {
            start.await();
            try { controller.add(7L,addBody(2)); return true; }
            catch (BizException rejected) { assertEquals(2006,rejected.getCode()); return false; }
        };
        try {
            var a=pool.submit(add); var b=pool.submit(add);
            assertEquals(1,(a.get(15,java.util.concurrent.TimeUnit.SECONDS)?1:0)+(b.get(15,java.util.concurrent.TimeUnit.SECONDS)?1:0));
            assertEquals(3,jdbc.queryForObject("select quantity from cart_item where id=1",Integer.class));
        } finally { pool.shutdownNow(); }
    }

    @Test void explicitSkuCannotSilentlyBecomeNoSkuWhenAllSkusDisabled() {
        jdbc.update("update mall_sku set status='DISABLE'");
        assertEquals(2108,assertThrows(BizException.class,() -> controller.add(7L,addBody(1))).getCode());
        assertEquals(0,jdbc.queryForObject("select count(*) from cart_item",Integer.class));
    }
    @Test void foreignSkuCannotSilentlyBecomeNoSkuOnSkuLessProduct() {
        jdbc.update("update mall_sku set product_id=2");
        assertEquals(2108,assertThrows(BizException.class,() -> controller.add(7L,addBody(1))).getCode());
        assertEquals(0,jdbc.queryForObject("select count(*) from cart_item",Integer.class));
    }
    @Test void omittedSkuOnProductWithOnlyDisabledSkusIsRejected() {
        jdbc.update("update mall_sku set status='DISABLE'"); var body=addBody(1); body.setSkuId(null);
        assertEquals(2108,assertThrows(BizException.class,() -> controller.add(7L,body)).getCode());
    }

    @Test void listReportsEffectiveSkuStockRatherThanProductAggregate() {
        row(1,7,11,2);
        List<?> rows=(List<?>)controller.list(7L).getData().get("items");
        assertEquals(3,((Map<?,?>)rows.get(0)).get("stock"));
        jdbc.update("update product set stock=1 where id=1");
        rows=(List<?>)controller.list(7L).getData().get("items");
        assertEquals(1,((Map<?,?>)rows.get(0)).get("stock"));
    }

}
